// Package zlib is a pure-Go implementation of zlib (RFC 1950) / deflate
// (RFC 1951) that produces byte-identical output to the C zlib reference
// implementation (madler/zlib 1.3 / 1.3.1). The algorithms, parameter tables,
// hash function, lazy-match heuristic, Huffman construction and block emission
// have been ported line-for-line from deflate.c and trees.c so that, for the
// same input, level, strategy, windowBits and memLevel, the output bytes
// match libz exactly.
//
// Decoding is RFC-compliant; matching libz's compressed output is not a
// meaningful concept for the decoder (decoded bytes are decoded bytes).
package zlib

